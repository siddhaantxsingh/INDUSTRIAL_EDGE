"""Write vectors.h: 18 test windows (3 per class) and the expected int8
logits from the Python integer reference, for the on-board check.
Run from the project root after tinyml/run_all.sh (needs tinyml/data)."""
import json
import os
import sys

import numpy as np

sys.path.insert(0, "tinyml")
from edgeml import ref  # noqa: E402

te = ref.load_bin("tinyml/data/test.bin")
info = json.load(open("tinyml/model/model.json"))
exp = np.fromfile("tinyml/data/test_expected.bin", dtype=np.uint8).reshape(-1, 22 * 4 + 22 + 6)
idx = [int(i) for c in range(6) for i in np.where(te["label"] == c)[0][:3]]
lines = ["/* Generated by tinyml/board/gen_vectors.py: SYNTHETIC test windows. */", "#include <stdint.h>",
         f"#define NVEC {len(idx)}"]
lines.append("static const int16_t vec_x[NVEC][1024] = {")
for i in idx:
    lines.append("{" + ",".join(str(int(v)) for v in te["x"][i]) + "},")
lines.append("};")
lines.append("static const uint16_t vec_rpm[NVEC] = {" + ",".join(str(int(te["rpm"][i])) for i in idx) + "};")
lines.append("static const uint16_t vec_cur[NVEC] = {" + ",".join(str(int(te["cur"][i])) for i in idx) + "};")
lines.append("static const int8_t vec_logits[NVEC][6] = {")
for i in idx:
    lines.append("{" + ",".join(str(int(np.int8(v))) for v in exp[i, -6:].view(np.int8)) + "},")
lines.append("};")
os.makedirs("tinyml/board/build", exist_ok=True)
open("tinyml/board/build/vectors.h", "w").write("\n".join(lines) + "\n")
print("wrote tinyml/board/build/vectors.h with", len(idx), "windows")
